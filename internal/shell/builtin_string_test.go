func TestStringBuiltin(t *testing.T) {
	for _, tc := range stringTests {
		out, errOut, status := runFish(t, tc.src)
		firstErr, _, _ := strings.Cut(errOut, "\n")
		if out != tc.out || status != tc.status || firstErr != tc.err {
			t.Errorf("%s\n got: %q status %d stderr %q\nwant: %q status %d stderr %q",
				tc.src, out, status, firstErr, tc.out, tc.status, tc.err)
		}
	}
}

// TestStringStdin checks where strings come from without operands: like
// fish, stdin is read only when it was redirected for the command, never
// the shell's own stdin.
func TestStringStdin(t *testing.T) {
	r, w, err := os.Pipe()
	if err != nil {
		t.Fatal(err)
	}
	defer r.Close()
	w.WriteString("data\n")
	w.Close()
	sh := New()
	sh.Init()
	sh.Stdin = r
	out := &lockedBuffer{}
	io := &IO{In: &Stream{File: r}, Out: &Stream{W: out}, Err: &Stream{W: &lockedBuffer{}}}
	sh.RunString("string upper; echo $status; string upper </dev/null; echo $status; cat | string upper", "test.fish", io)
	if got, want := out.String(), "1\n1\nDATA\n"; got != want {
		t.Errorf("inherited stdin: got %q, want %q", got, want)
	}

	path := filepath.Join(t.TempDir(), "in.txt")
	if err := os.WriteFile(path, []byte("hello\nworld"), 0o644); err != nil {
		t.Fatal(err)
	}
	got, _, status := runFish(t, "string upper <"+Quote(path)+"; string length <"+Quote(path))
	if want := "HELLO\nWORLD5\n5\n"; got != want || status != 0 {
		t.Errorf("file redirect: got %q status %d, want %q status 0", got, status, want)
	}
}

// TestStringRegexUnsupported checks that PCRE2 features RE2 lacks are
// reported as compile errors rather than silently misbehaving.
func TestStringRegexUnsupported(t *testing.T) {
	for _, src := range []string{
		`string match -r '(a)\1' aa`,
		`string match -r 'a(?=b)' ab`,
		`string replace -r '(?<=a)b' x ab`,
		`string match -r 'a\Kb' ab`,
	} {
		out, errOut, status := runFish(t, src)
		if out != "" || status != 2 || !strings.Contains(errOut, ": Regular expression compile error: ") {
			t.Errorf("%s: got %q status %d stderr %q", src, out, status, errOut)
		}
	}
}

